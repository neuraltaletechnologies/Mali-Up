final Map<String, Country> _byCode = {
  for (final c in kCountries) c.code: c,
};

/// Looks up a country by alpha-2 code (case-insensitive). Null if unknown.
Country? countryByCode(String? code) =>
    (code == null || code.isEmpty) ? null : _byCode[code.toUpperCase()];

/// Display name for [code], or the code itself if it isn't in the table.
String countryNameOrCode(String code) => countryByCode(code)?.name ?? code;
