/// ISO 3166-1 country list for the business-location picker.
///
/// This is a plain name + alpha-2 table. The flag emoji is derived from the
/// code (regional-indicator symbols) so there is nothing to keep in sync, and
/// the alpha-2 code is what [GeoLookupService] passes to the Country-State-City
/// API. Tanzania is pinned first (the app's home market); the rest follow
/// alphabetically by English name.
library;

class Country {
  const Country(this.code, this.name);

  /// ISO 3166-1 alpha-2, uppercase (e.g. `TZ`).
  final String code;

  /// English display name.
  final String name;

  /// `🇹🇿`-style flag built from [code]'s two regional-indicator symbols.
  /// Falls back to a neutral white flag for anything that isn't A–Z × 2.
  String get flag {
    if (code.length != 2) return '\u{1F3F3}\u{FE0F}';
    const base = 0x1F1E6; // regional indicator 'A'
    final a = code.codeUnitAt(0);
    final b = code.codeUnitAt(1);
    if (a < 0x41 || a > 0x5A || b < 0x41 || b > 0x5A) {
      return '\u{1F3F3}\u{FE0F}';
    }
    return String.fromCharCodes([base + (a - 0x41), base + (b - 0x41)]);
  }
}

